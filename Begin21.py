x1 = float(input("Введите кординату"))
x2 = float(input("Введите кординату"))
x3 = float(input("Введите кординату"))
y1 = float(input("Введите кординату"))
y2 = float(input("Введите кординату"))
y3 = float(input("Введите кординату"))
a = ((x2 - x1)**2 + (y2 - y1)**2)**0.5
b = ((x3 - x2)**2 + (y3 - y2)**2)**0.5
c = ((x1 - x3)**2 + (y1 - y3)**2)**0.5
P = (a + b + c)
p = P / 2
S = (p * (p - a) * (p - b) * (p - c))**0.5
print(f"полупериметр {p}", f"периметр {P}", f"площадь {S}")